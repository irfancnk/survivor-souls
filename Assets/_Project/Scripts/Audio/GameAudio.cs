using SurvivorSouls.Gameplay.Combat;
using SurvivorSouls.Gameplay.Player;
using SurvivorSouls.Gameplay.Progression;
using SurvivorSouls.Gameplay.Skills;
using SurvivorSouls.UI.Hud;
using UnityEngine;

namespace SurvivorSouls.Audio
{
    /// <summary>
    /// Game scene sound: crossbow shots, bolt impacts, hit / kill marker ticks, enemy deaths, player hurt + death, soul wisp chimes + level-up + boon pick + HUD skill level-up chime (KAN-74) + skill card reveal per tier (KAN-37, clip and volume from the card's
    /// <see cref="SkillRarityStyles"/>), the portal opening horn (KAN-39), the portal rush + Chamber toll (KAN-40), a low horn + toll when the Realm is cleared (KAN-47), the knight's footsteps in snow and a
    /// looping ambience (wind + surf + distant gulls). Boss (KAN-58): a deep groan when it rises and when it falls, a heavy
    /// thud when the slam lands (death and impact clips pitched far down; own clips can come later); a soft warm swell when the
    /// Knight takes a healing heart (KAN-60). All clips are generated by the editor (SfxBuilder, no paid assets).
    /// 2D playback through a small round-robin pool; pitch and clip vary per play so repeats do not sound robotic.
    /// Volumes follow <see cref="GameSettings"/> (SFX volume for effects, music volume for ambience).
    /// </summary>
    public sealed class GameAudio : MonoBehaviour
    {
        [Header("Sources")]
        [SerializeField] private AutoShooter shooter;
        [SerializeField] private PlayerMover player;
        [SerializeField] private PlayerHealth playerHealth;
        [SerializeField] private SoulWispField souls;
        [SerializeField] private LevelUpFlow levelUp;
        [SerializeField] private SkillManager skills;
        [SerializeField] private SurvivalTimer timer;
        [SerializeField] private ChamberTransition transition;
        [SerializeField] private BossFight boss;
        [Tooltip("Boss fight healing hearts (KAN-60): soft swell on pickup.")]
        [SerializeField] private BossHearts hearts;
        [Tooltip("Level-up cards: each card landing plays its tier's reveal sound (KAN-37).")]
        [SerializeField] private SkillChoiceScreen skillChoice;
        [Tooltip("Reliquary chests (KAN-73): land thud, open creak + shimmer.")]
        [SerializeField] private ChestDropper chests;
        [Tooltip("HUD skill row (KAN-74): chime when an owned skill's slot glows after a level-up.")]
        [SerializeField] private SkillHud skillHud;

        [Header("Clips")]
        [SerializeField] private AudioClip[] shots;
        [SerializeField] private AudioClip[] impacts;
        [SerializeField] private AudioClip[] deaths;
        [SerializeField] private AudioClip[] footsteps;
        [Tooltip("Hit marker confirm tick (KAN-13), plays on every non-lethal enemy hit.")]
        [SerializeField] private AudioClip[] hitMarkers;
        [Tooltip("Kill marker confirm (KAN-13), plays on the killing blow.")]
        [SerializeField] private AudioClip[] killMarkers;
        [Tooltip("Soul wisp absorbed (KAN-21). Pitch climbs while pickups come in a row.")]
        [SerializeField] private AudioClip[] soulChimes;
        [Tooltip("Level-up swell (KAN-21), plays while the game is paused.")]
        [SerializeField] private AudioClip[] levelUps;
        [SerializeField] private AudioClip[] boonPicks;
        [SerializeField] private AudioClip[] chestDrops;
        [SerializeField] private AudioClip[] chestOpens;
        [Tooltip("Owned skill levelled up: HUD glow chime (KAN-74).")]
        [SerializeField] private AudioClip[] skillUpgrades;
        [Tooltip("Healing heart taken (KAN-60).")]
        [SerializeField] private AudioClip[] heartHeals;
        [Tooltip("Survival timer ended: horn + chime (KAN-39). 2D, heard anywhere; the portal's own hum is 3D.")]
        [SerializeField] private AudioClip[] portalOpens;
        [Tooltip("Knight steps into the portal: rush into the white (KAN-40).")]
        [SerializeField] private AudioClip[] portalEnters;
        [Tooltip("New Chamber begins after a portal: one bell toll under the title card (KAN-40).")]
        [SerializeField] private AudioClip[] chamberArrives;
        [SerializeField] private AudioClip ambience;

        [Header("Mix")]
        [SerializeField, Range(0f, 1f)] private float shotVolume = 0.8f;
        [Tooltip("Double Shot follow-up bolt (KAN-83): a quiet extra shot layer, as a share of the shot volume, pitched up a little.")]
        [SerializeField, Range(0f, 1f)] private float followUpShotShare = 0.35f;
        [SerializeField, Range(0.5f, 2f)] private float followUpShotPitch = 1.1f;
        [SerializeField, Range(0f, 1f)] private float impactVolume = 0.75f;
        [SerializeField, Range(0f, 1f)] private float deathVolume = 0.7f;
        [SerializeField, Range(0f, 1f)] private float footstepVolume = 0.35f;
        [SerializeField, Range(0f, 1f)] private float ambienceVolume = 0.45f;
        [Tooltip("Player hurt pulse: an impact clip pitched down.")]
        [SerializeField, Range(0f, 1f)] private float hurtVolume = 0.55f;
        [SerializeField, Range(0.3f, 1.5f)] private float hurtPitch = 0.72f;
        [Tooltip("Player death: an enemy death clip pitched down.")]
        [SerializeField, Range(0f, 1f)] private float playerDeathVolume = 0.9f;
        [SerializeField, Range(0.3f, 1.5f)] private float playerDeathPitch = 0.62f;
        [SerializeField, Range(0f, 1f)] private float hitMarkerVolume = 0.32f;
        [SerializeField, Range(0f, 1f)] private float killMarkerVolume = 0.5f;
        [Tooltip("Minimum seconds between two marker sounds: several bolts landing in one frame give one tick, not a flange.")]
        [SerializeField, Min(0f)] private float markerInterval = 0.04f;
        [Tooltip("Minimum seconds between two enemy death groans (a horde dying to one soul burst gives a few, not a wall).")]
        [SerializeField, Min(0f)] private float deathInterval = 0.07f;
        [SerializeField, Range(0f, 1f)] private float soulVolume = 0.4f;
        [SerializeField, Range(0f, 1f)] private float levelUpVolume = 0.8f;
        [SerializeField, Range(0f, 1f)] private float boonPickVolume = 0.75f;
        [SerializeField, Range(0f, 1f)] private float skillUpgradeVolume = 0.6f;
        [SerializeField, Range(0f, 1f)] private float portalOpenVolume = 0.85f;
        [SerializeField, Range(0f, 1f)] private float portalEnterVolume = 0.8f;
        [SerializeField, Range(0f, 1f)] private float chamberArriveVolume = 0.7f;
        [Header("Boss (KAN-58)")]
        [SerializeField, Range(0f, 1f)] private float bossGroanVolume = 0.95f;
        [SerializeField, Range(0.2f, 1.5f)] private float bossGroanPitch = 0.45f;
        [SerializeField, Range(0f, 1f)] private float slamVolume = 1f;
        [SerializeField, Range(0.2f, 1.5f)] private float slamPitch = 0.4f;
        [Tooltip("Boss fan volley (KAN-61): the crossbow shot clip, pitched down.")]
        [SerializeField, Range(0f, 1f)] private float fanVolume = 0.8f;
        [SerializeField, Range(0.2f, 1.5f)] private float fanPitch = 0.55f;
        [Tooltip("Fan bolt hits a pillar or the wall.")]
        [SerializeField, Range(0f, 1f)] private float boltBlockVolume = 0.35f;
        [SerializeField, Range(0.2f, 2f)] private float boltBlockPitch = 1.25f;
        [Tooltip("Boss phase 2 roar: the groan, higher.")]
        [SerializeField, Range(0.2f, 1.5f)] private float phaseRoarPitch = 0.6f;
        [SerializeField, Range(0f, 1f)] private float heartHealVolume = 0.7f;
        [Tooltip("Minimum seconds between two soul chimes (a pile absorbed in one frame gives one chime).")]
        [SerializeField, Min(0f)] private float soulInterval = 0.035f;
        [Tooltip("A pickup within this many seconds of the last one continues the streak (pitch keeps climbing).")]
        [SerializeField, Min(0f)] private float soulStreakWindow = 0.6f;
        [Tooltip("Semitones added per pickup in a streak.")]
        [SerializeField, Min(0f)] private float soulStreakStep = 1f;
        [Tooltip("Streak steps after which the pitch stops climbing.")]
        [SerializeField, Min(0)] private int soulStreakMax = 9;
        [SerializeField, Min(1)] private int voices = 8;
        [Tooltip("Metres walked per footstep (one foot).")]
        [SerializeField, Min(0.1f)] private float strideLength = 0.75f;

        private AudioSource[] _pool;
        private AudioSource _ambience;
        private int _next;
        private float _stepDistance;
        private int _lastClip = -1;
        private float _lastMarker = float.NegativeInfinity;
        private float _lastDeath = float.NegativeInfinity;
        private float _lastSoul = float.NegativeInfinity;
        private float _lastSoulChime = float.NegativeInfinity;
        private int _soulStreak;

        private void Awake()
        {
            _pool = new AudioSource[voices];
            for (int i = 0; i < voices; i++) _pool[i] = NewSource($"Voice {i}");
            _ambience = NewSource("Ambience");
            _ambience.loop = true;
            _ambience.clip = ambience;
        }

        private void OnEnable()
        {
            if (shooter != null)
            {
                shooter.Fired += OnFired;
                shooter.FollowUpFired += OnFollowUpFired;
            }
            Bolt.Hit += OnHit;
            Enemy.Damaged += OnDamaged;
            if (playerHealth != null)
            {
                playerHealth.OnHurt += OnPlayerHurt;
                playerHealth.OnDeath += OnPlayerDeath;
            }
            if (souls != null) souls.Collected += OnSoulCollected;
            if (levelUp != null) levelUp.Started += OnLevelUp;
            if (skills != null) skills.Granted += OnSkillGranted;
            if (skillChoice != null)
            {
                skillChoice.CardRevealed += OnCardRevealed;
                skillChoice.Upgraded += OnSkillUpgraded;
            }
            if (skillHud != null) skillHud.UpgradeShown += OnUpgradeShown;
            if (chests != null)
            {
                chests.Dropped += OnChestDropped;
                chests.OpenStarted += OnChestOpened;
            }
            if (timer != null) timer.Finished += OnPortalOpens;
            if (transition != null)
            {
                transition.Departing += OnPortalEntered;
                transition.Arrived += OnChamberArrived;
                transition.RealmCleared += OnRealmCleared;
            }
            if (boss != null)
            {
                boss.Spawned += OnBossSpawned;
                boss.Slammed += OnBossSlammed;
                boss.Defeated += OnBossDefeated;
                boss.PhaseChanged += OnBossPhase;
                boss.FanFired += OnBossFan;
                boss.Charged += OnBossCharged;
                boss.LaneStruck += OnBossLane;
                boss.SpinHit += OnBossSpinHit;
                if (boss.Projectiles != null) boss.Projectiles.Blocked += OnBoltBlocked;
            }
            if (hearts != null) hearts.PickedUp += OnHeartPickedUp;
            GameSettings.Changed += ApplyVolumes;
            ApplyVolumes();
            if (_ambience.clip != null) _ambience.Play();
        }

        private void OnDisable()
        {
            if (shooter != null)
            {
                shooter.Fired -= OnFired;
                shooter.FollowUpFired -= OnFollowUpFired;
            }
            Bolt.Hit -= OnHit;
            Enemy.Damaged -= OnDamaged;
            if (playerHealth != null)
            {
                playerHealth.OnHurt -= OnPlayerHurt;
                playerHealth.OnDeath -= OnPlayerDeath;
            }
            if (souls != null) souls.Collected -= OnSoulCollected;
            if (levelUp != null) levelUp.Started -= OnLevelUp;
            if (skills != null) skills.Granted -= OnSkillGranted;
            if (skillChoice != null)
            {
                skillChoice.CardRevealed -= OnCardRevealed;
                skillChoice.Upgraded -= OnSkillUpgraded;
            }
            if (skillHud != null) skillHud.UpgradeShown -= OnUpgradeShown;
            if (chests != null)
            {
                chests.Dropped -= OnChestDropped;
                chests.OpenStarted -= OnChestOpened;
            }
            if (timer != null) timer.Finished -= OnPortalOpens;
            if (transition != null)
            {
                transition.Departing -= OnPortalEntered;
                transition.Arrived -= OnChamberArrived;
                transition.RealmCleared -= OnRealmCleared;
            }
            if (boss != null)
            {
                boss.Spawned -= OnBossSpawned;
                boss.Slammed -= OnBossSlammed;
                boss.Defeated -= OnBossDefeated;
                boss.PhaseChanged -= OnBossPhase;
                boss.FanFired -= OnBossFan;
                boss.Charged -= OnBossCharged;
                boss.LaneStruck -= OnBossLane;
                boss.SpinHit -= OnBossSpinHit;
                if (boss.Projectiles != null) boss.Projectiles.Blocked -= OnBoltBlocked;
            }
            if (hearts != null) hearts.PickedUp -= OnHeartPickedUp;
            GameSettings.Changed -= ApplyVolumes;
        }

        private void Update()
        {
            if (player == null) return;
            Vector3 v = player.Velocity;
            v.y = 0f;
            float speed = v.magnitude;
            if (speed < 0.3f) { _stepDistance = strideLength * 0.5f; return; } // first step comes quickly
            _stepDistance += speed * Time.deltaTime;
            if (_stepDistance < strideLength) return;
            _stepDistance -= strideLength;
            Play(footsteps, footstepVolume * Mathf.Lerp(0.7f, 1f, speed / 5f), 0.08f);
        }

        private void OnFired(Vector3 muzzle, Vector3 direction) => Play(shots, shotVolume, 0.06f);
        private void OnFollowUpFired(Vector3 muzzle, Vector3 direction) =>
            Play(shots, shotVolume * followUpShotShare, 0.04f, followUpShotPitch);
        private void OnHit(Vector3 point, Vector3 direction) => Play(impacts, impactVolume, 0.1f);

        private void OnDamaged(Enemy enemy, float amount, bool killed)
        {
            if (killed && Time.unscaledTime - _lastDeath >= deathInterval)
            {
                _lastDeath = Time.unscaledTime;
                Play(deaths, deathVolume, 0.08f);
            }
            // Kill always sounds (it is the payoff); hit ticks are rate limited and only for the player's own bolts.
            if (!killed && (enemy.LastDamageKind != DamageKind.Direct || Time.unscaledTime - _lastMarker < markerInterval)) return;
            _lastMarker = Time.unscaledTime;
            if (killed) Play(killMarkers, killMarkerVolume, 0.02f);
            else Play(hitMarkers, hitMarkerVolume, 0.04f);
        }

        private void OnPlayerHurt()
        {
            if (!playerHealth.IsDead) Play(impacts, hurtVolume, 0.06f, hurtPitch);
        }

        private void OnSoulCollected(Vector3 point, int xp)
        {
            float now = Time.unscaledTime;
            _soulStreak = now - _lastSoul <= soulStreakWindow ? _soulStreak + 1 : 0;
            _lastSoul = now;
            if (now - _lastSoulChime < soulInterval) return;
            _lastSoulChime = now;
            float semitones = Mathf.Min(_soulStreak, soulStreakMax) * soulStreakStep;
            Play(soulChimes, soulVolume, 0.01f, Mathf.Pow(2f, semitones / 12f));
        }

        private void OnLevelUp(int level) => Play(levelUps, levelUpVolume, 0f);

        private void OnSkillGranted(SkillDefinition skill, int stacks) => Play(boonPicks, boonPickVolume, 0f);

        /// <summary>Chest upgrade picked: the boon strike a fifth higher (same family, reads as "more of it").</summary>
        private void OnSkillUpgraded(SkillDefinition skill, int oldLevel, int newLevel) =>
            Play(boonPicks, boonPickVolume, 0f, 1.335f);

        /// <summary>HUD slot glow after a level-up (KAN-74): one chime per batch, however many slots glow.</summary>
        private void OnUpgradeShown(int slots) => Play(skillUpgrades, skillUpgradeVolume, 0.02f);

        private void OnChestDropped(ReliquaryChest chest) => Play(chestDrops, boonPickVolume * 0.8f, 0.04f);

        private void OnChestOpened(ReliquaryChest chest) => Play(chestOpens, boonPickVolume, 0.02f);

        private void OnCardRevealed(int index, SkillDefinition skill)
        {
            var style = skillChoice.StyleOf(skill.Rarity);
            if (style.reveal == null) return;
            var src = _pool[_next];
            _next = (_next + 1) % _pool.Length;
            src.pitch = 1f + index * 0.02f; // three cards in a row: a hair brighter each, never a flange
            src.PlayOneShot(style.reveal, style.revealVolume * GameSettings.SfxVolume);
        }

        private void OnPortalOpens() => Play(portalOpens, portalOpenVolume, 0f);

        private void OnPortalEntered() => Play(portalEnters, portalEnterVolume, 0f);

        private void OnChamberArrived(int chamber) => Play(chamberArrives, chamberArriveVolume, 0f);

        /// <summary>End of Realm (KAN-47): the portal horn a little lower, under the Chamber toll.</summary>
        private void OnRealmCleared(SurvivorSouls.Gameplay.Chamber.RunSnapshot run)
        {
            Play(portalOpens, portalOpenVolume, 0f, 0.84f);
            Play(chamberArrives, chamberArriveVolume, 0f);
        }

        private void OnBossSpawned(Enemy body) => Play(deaths, bossGroanVolume, 0.02f, bossGroanPitch);
        private void OnBossSlammed(Vector3 centre, float dealt) => Play(impacts, slamVolume, 0.03f, slamPitch);
        private void OnBossPhase(int phase) => Play(deaths, bossGroanVolume, 0.02f, phaseRoarPitch);
        private void OnBossFan(Vector3 origin, int bolts) => Play(shots, fanVolume, 0.03f, fanPitch);
        private void OnBossCharged(Vector3 end, float dealt) => Play(impacts, slamVolume, 0.03f, slamPitch * 1.15f);
        private void OnBossLane(Vector3 mid, float dealt) => Play(impacts, slamVolume, 0.03f, slamPitch * 1.08f);
        private void OnBossSpinHit(Vector3 at, float dealt) => Play(impacts, slamVolume * 0.6f, 0.05f, slamPitch * 1.3f);
        private void OnBoltBlocked(Vector3 at) => Play(impacts, boltBlockVolume, 0.08f, boltBlockPitch);
        private void OnBossDefeated() => Play(deaths, bossGroanVolume, 0.02f, bossGroanPitch * 0.85f);
        private void OnHeartPickedUp(HealingHeart heart, float healed) => Play(heartHeals, heartHealVolume, 0.02f);

        private void OnPlayerDeath() => Play(deaths, playerDeathVolume, 0.03f, playerDeathPitch);

        private void Play(AudioClip[] clips, float volume, float pitchJitter, float pitch = 1f)
        {
            if (clips == null || clips.Length == 0) return;
            int i = Random.Range(0, clips.Length);
            if (clips.Length > 1 && i == _lastClip) i = (i + 1) % clips.Length;
            _lastClip = i;
            var src = _pool[_next];
            _next = (_next + 1) % _pool.Length;
            src.pitch = pitch + Random.Range(-pitchJitter, pitchJitter);
            src.PlayOneShot(clips[i], volume * GameSettings.SfxVolume);
        }

        private void ApplyVolumes()
        {
            if (_ambience != null) _ambience.volume = ambienceVolume * GameSettings.MusicVolume;
        }

        private AudioSource NewSource(string name)
        {
            var go = new GameObject(name);
            go.transform.SetParent(transform, false);
            var src = go.AddComponent<AudioSource>();
            src.playOnAwake = false;
            src.spatialBlend = 0f;
            return src;
        }
    }
}
